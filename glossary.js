export function mountGlossary() {
  document.addEventListener('click', event => {
    const t = event.target.closest('[data-term]');
    if (t) { event.preventDefault(); openTerm(t.dataset.term); return; }
    if (event.target.closest('.sheet-guide')) { openGuide(); return; }
    if (event.target.closest('#sheet [data-close]')) { closeSheet(); return; }
    if (event.target.closest('#btn-guide')) openGuide();
  });
  document.addEventListener('keydown', event => { if (event.key === 'Escape') closeSheet(); });
}

