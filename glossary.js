// 照合用: 言い方 → 用語。長い言い方から先に当てる
const WORDS = Object.entries(TERMS).flatMap(([key, t]) => t.words.map(w => ({ w, key }))).sort((a, b) => b.w.length - a.w.length);
// 1文字の言い方 (「追」「◎」など) は、文章中では誤って拾いやすいので、文章の用語リンクには使わない
const LINK_RE = new RegExp(WORDS.filter(x => x.w.length >= 2).map(x => x.w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
const KEY_OF = Object.fromEntries(WORDS.map(x => [x.w, x.key]));

// 文章の中の用語を、タップできる形にする。seen (Set) を渡すと、同じ用語は最初の1回だけにする (下線だらけにしない)
export function linkTerms(text, seen = null) {
  const s = String(text ?? '');
  let out = '', last = 0;
  for (const m of s.matchAll(LINK_RE)) {
    const key = KEY_OF[m[0]];
    out += esc(s.slice(last, m.index));
    if (key && (!seen || !seen.has(key))) {
      seen?.add(key);
      out += `<button type="button" class="term" data-term="${esc(key)}">${esc(m[0])}</button>`;
    } else out += esc(m[0]);
    last = m.index + m[0].length;
  }
  return out + esc(s.slice(last));
}

// ---------- 下から出るシート ----------
let lastFocus = null;
export function openSheet(title, html) {
  const sheet = document.getElementById('sheet');
  if (!sheet) return;
  lastFocus = document.activeElement;
  sheet.querySelector('#sheet-title').textContent = title;
  sheet.querySelector('.sheet-content').innerHTML = html;
  sheet.hidden = false;
  sheet.querySelector('.sheet-body').scrollTop = 0;
  document.body.classList.add('sheet-open');
  sheet.querySelector('.sheet-close')?.focus({ preventScroll: true });
}
export function closeSheet() {
  const sheet = document.getElementById('sheet');
  if (!sheet || sheet.hidden) return;
  sheet.hidden = true;
  document.body.classList.remove('sheet-open');
  lastFocus?.focus?.({ preventScroll: true });
}

export function termHtml(key) {
  const t = TERMS[key];
  if (!t) return '';
  const alias = t.words.filter(w => w !== key && w.length >= 2).slice(0, 4);
  return `${alias.length ? `<p class="sheet-alias">${alias.map(esc).join('・')} とも</p>` : ''}
    <p class="sheet-text">${linkTerms(t.text, new Set([key]))}</p>
    ${t.see?.length ? `<div class="sheet-see"><span>関連:</span>${t.see.filter(k => TERMS[k]).map(k => `<button type="button" class="term-chip" data-term="${esc(k)}">${esc(k)}</button>`).join('')}</div>` : ''}
    <button type="button" class="secondary-btn sheet-guide">競輪の基本を最初から読む</button>`;
}
export function openTerm(key) { if (TERMS[key]) openSheet(key, termHtml(key)); }

